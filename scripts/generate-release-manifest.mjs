#!/usr/bin/env node
/**
 * generate-release-manifest.mjs
 *
 * Generates release-manifest.json by fetching real RepoDigests from the Docker registry.
 * Must be run after all 5 images have been built and pushed to the registry.
 *
 * Usage:
 *   node scripts/generate-release-manifest.mjs \
 *     --version=1.2.3 \
 *     --api=ghcr.io/org/restaurant-order-api:v1.2.3 \
 *     --worker=ghcr.io/org/restaurant-order-worker:v1.2.3 \
 *     --customer-web=ghcr.io/org/restaurant-order-customer-web:v1.2.3 \
 *     --operations-web=ghcr.io/org/restaurant-order-operations-web:v1.2.3 \
 *     --admin-web=ghcr.io/org/restaurant-order-admin-web:v1.2.3
 *
 * Environment variables (alternative to flags):
 *   API_IMAGE, WORKER_IMAGE, CUSTOMER_WEB_IMAGE, OPERATIONS_WEB_IMAGE, ADMIN_WEB_IMAGE
 *   RELEASE_VERSION, RELEASE_ID, GIT_SHA
 *
 * Output: release-manifest.json (listed in .gitignore — generated by CI/CD only)
 */

import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import fs from 'node:fs';
import path from 'node:path';
import { isValidDigest, isPlaceholderDigest, EMPTY_CONTENT_DIGEST } from './blue-green/lib/manifest.mjs';

const execFileAsync = promisify(execFile);

const MANIFEST_OUTPUT = path.join(process.cwd(), 'release-manifest.json');
const SCHEMA_REF = './docs/schemas/release-manifest.schema.json';

function parseArgs() {
  const args = process.argv.slice(2);
  const flags = {};
  for (const arg of args) {
    const [key, ...rest] = arg.replace(/^--/, '').split('=');
    flags[key] = rest.join('=');
  }
  return flags;
}

/**
 * Fetches the RepoDigest for an image from the local Docker daemon.
 * Requires the image to have been pulled or pushed.
 * Returns null if the image is not found or digest cannot be determined.
 */
async function fetchRepoDigest(imageRef) {
  try {
    // docker inspect returns RepoDigests which are the registry-assigned digests
    const { stdout } = await execFileAsync('docker', [
      'inspect',
      '--format', '{{index .RepoDigests 0}}',
      imageRef,
    ]);

    const digest = stdout.trim();
    if (!digest || digest === '<no value>') {
      return { success: false, error: `No RepoDigest found for '${imageRef}'. Pull or push the image first.` };
    }

    // RepoDigest format: ghcr.io/org/image@sha256:abc123
    const atIndex = digest.lastIndexOf('@');
    if (atIndex === -1) {
      return { success: false, error: `Unexpected RepoDigest format for '${imageRef}': ${digest}` };
    }

    const extractedDigest = digest.slice(atIndex + 1);

    if (!isValidDigest(extractedDigest)) {
      return { success: false, error: `Extracted digest '${extractedDigest}' from '${imageRef}' is not a valid sha256 digest.` };
    }

    if (isPlaceholderDigest(extractedDigest)) {
      if (extractedDigest.toLowerCase() === EMPTY_CONTENT_DIGEST) {
        return { success: false, error: `Image '${imageRef}' has the empty-content digest — the image was not actually built.` };
      }
      return { success: false, error: `Image '${imageRef}' has a placeholder all-zeros digest — the image was not pushed to a real registry.` };
    }

    return { success: true, digest: extractedDigest, repository: digest.slice(0, atIndex) };
  } catch (err) {
    return { success: false, error: `docker inspect failed for '${imageRef}': ${err.message}` };
  }
}

async function main() {
  const flags = parseArgs();

  const version = flags.version || process.env.RELEASE_VERSION;
  if (!version) {
    console.error('[ERROR] --version is required (e.g. --version=1.2.3)');
    process.exit(1);
  }

  const imageMap = {
    api: flags.api || process.env.API_IMAGE,
    worker: flags.worker || process.env.WORKER_IMAGE,
    'customer-web': flags['customer-web'] || process.env.CUSTOMER_WEB_IMAGE,
    'operations-web': flags['operations-web'] || process.env.OPERATIONS_WEB_IMAGE,
    'admin-web': flags['admin-web'] || process.env.ADMIN_WEB_IMAGE,
  };

  const missingImages = Object.entries(imageMap)
    .filter(([, ref]) => !ref)
    .map(([key]) => key);

  if (missingImages.length > 0) {
    console.error(`[ERROR] Missing image references for: ${missingImages.join(', ')}`);
    console.error('Provide each via flag (--api=...) or environment variable (API_IMAGE=...)');
    process.exit(1);
  }

  console.log('[INFO] Fetching RepoDigests from Docker daemon...');
  const images = {};
  const errors = [];

  for (const [key, imageRef] of Object.entries(imageMap)) {
    process.stdout.write(`  ${key}: ${imageRef} ... `);
    const result = await fetchRepoDigest(imageRef);

    if (!result.success) {
      console.log('BLOCKED');
      errors.push(`  [BLOCKED] ${key}: ${result.error}`);
    } else {
      console.log(`OK (${result.digest.slice(0, 19)}...)`);
      const colonIdx = imageRef.lastIndexOf(':');
      const tag = colonIdx > imageRef.lastIndexOf('/') ? imageRef.slice(colonIdx + 1) : 'unknown';
      images[key] = {
        repository: result.repository,
        tag,
        digest: result.digest,
      };
    }
  }

  if (errors.length > 0) {
    console.error('\n[FAIL] Cannot generate manifest due to the following errors:');
    errors.forEach((e) => console.error(e));
    console.error('\nResolve these issues and re-run after all images are pushed to the registry.');
    process.exit(1);
  }

  const manifest = {
    $schema: SCHEMA_REF,
    version,
    releaseId: flags.releaseId || process.env.RELEASE_ID || `rel-${version}-${Date.now()}`,
    createdAt: new Date().toISOString(),
    gitSha: flags.gitSha || process.env.GIT_SHA || process.env.GITHUB_SHA || null,
    images,
  };

  fs.writeFileSync(MANIFEST_OUTPUT, JSON.stringify(manifest, null, 2) + '\n', 'utf8');
  console.log(`\n[PASS] release-manifest.json generated at ${MANIFEST_OUTPUT}`);
  console.log(`  Version: ${version}`);
  console.log(`  Images: ${Object.keys(images).join(', ')}`);
}

main().catch((err) => {
  console.error('[FATAL]', err.message);
  process.exit(1);
});
